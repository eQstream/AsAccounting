#pragma once
#include "domain/Owner.h"
#include <string>

/// @brief Агрегат — машиноместо в гаражном кооперативе.
///
/// Корень агрегата. Содержит номер места, владельца и заметки.
/// Владелец (Owner) является value object — при смене заменяется целиком.
class Spot
{
public:
    /// @brief Создаёт место с заданным номером, владельцем и заметками.
    /// @param id Номер машиноместа
    /// @param owner Владелец места
    /// @param notes Заметки (по умолчанию пусто)
    Spot(int id, Owner owner, std::string notes = "");

    /// @brief Создаёт свободное место без владельца.
    /// @param id Номер машиноместа
    explicit Spot(int id);

    // ============================================================
    // Геттеры
    // ============================================================

    int getId() const;
    const Owner &getOwner() const;
    const std::string &getNotes() const;

    // ============================================================
    // Бизнес-логика
    // ============================================================

    /// @return Базовый ежемесячный взнос в зависимости от номера места.
    ///         id <= 150 → 1300 руб., id > 150 → 2000 руб.
    int getBaseMonthlyPayment() const;

    /// @return Итоговый взнос с учётом льгот владельца.
    int getFinalPayment() const;

    // ============================================================
    // Мутация
    // ============================================================

    /// @brief Замена владельца (value object — заменяется целиком).
    /// @param owner Новый владелец
    void setOwner(Owner owner);

    /// @brief Установка заметок.
    /// @param notes Новые заметки
    void setNotes(const std::string &notes);

private:
    int id;
    Owner owner;
    std::string notes;
};